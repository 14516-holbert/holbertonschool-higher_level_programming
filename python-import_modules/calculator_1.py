def add(a, b):
    """Return the addition of a and b."""
    return (a + b)
def vurma(a, b):
    """Return the multiplication of a and b."""
    return a * b
def bolme(a, b):
    """Return the division of a and b."""
    return a / b
def cixma(a, b):
    """Return the subtraction of a and b."""
    return a - b
